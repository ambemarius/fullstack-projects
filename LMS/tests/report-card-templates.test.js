test('every template renders a complete A4 page with no missing values', async () => {
    const fmt = bulletin.formatters;
    const base = cards(3, { discipline: { a: { absences: 4, justified: 3, unjustified: 1, lateness: 2 } } }).map(c => ({ ...c, barcode: '<svg></svg>' }));
    const expect = { anglophone: 'CLASS COUNCIL DECISION', francophone: 'DÉCISION DU CONSEIL DE CLASSE', technical: 'CLASS COUNCIL DECISION | DÉCISION DU CONSEIL DE CLASSE' };
    for (const [id, heading] of Object.entries(expect)) {
        const html = await ejs.renderFile(path.join(__dirname, '../views/report-card-minesec.ejs'),
            { className: 'Form 4A', term: 'Third', yearName: '2026-2027', cards: base.map(c => decorate(c, id)), fmt });
        assert.ok(html.includes(heading), id);
        assert.equal((html.match(/class="page"/g) || []).length, 3, `${id}: one page per student`);
        assert.equal(/undefined|NaN|\[object/.test(html), false, `${id}: no missing values`);
        assert.equal(/<script(?![^>]*\bsrc=)/.test(html), false, `${id}: no inline script`);
        assert.match(html, /66\.7%/, `${id}: pass rate`);
    }
});

test('the print page uses the saved template, a template asked for in the URL, or the section for "auto"', async () => {
    const render = async (query, saved, section = 'Anglophone') => {
        let view, locals;
        const req = { query: { classId: '1', term: 'Third', yearId: '1', ...query }, app: { locals: { reportCardService: {
            classCards: async () => ({ className: 'Form 4A', yearName: '2026-2027', term: 'Third', section, template: saved, cards: cards(3) }),
        } } } };
        const res = { set() { return this; }, render(v, l) { view = v; locals = l; } };
        await bulletin.printPage(req, res, err => { throw err; });
        return { view, template: locals.template, first: locals.cards[0] };
    };
    assert.deepEqual((await render({}, 'classic')).view, 'report-card-print');
    const saved = await render({}, 'francophone');
    assert.equal(saved.view, 'report-card-minesec');
    assert.equal(saved.first.tpl.L.lang, 'fr');
    assert.equal((await render({ template: 'technical' }, 'classic')).template, 'technical', 'the URL choice wins');
    assert.equal((await render({ template: 'bogus' }, 'anglophone')).template, 'anglophone', 'an unknown choice falls back to the saved one');
    assert.equal((await render({}, 'auto', 'Francophone')).template, 'francophone');
});

test('saving a template refuses unknown names before any SQL', async () => {
    const { createReportCardService } = require('../model/Academic/reportCardService');
    let touched = false;
    const service = createReportCardService({ read: async () => { touched = true; return { recordset: [] }; }, beginTransaction: async () => { touched = true; } });
    await assert.rejects(service.saveTemplate({ id: 7 }, 1, 'fancy'), err => err.statusCode === 422);
    assert.equal(touched, false);
});
