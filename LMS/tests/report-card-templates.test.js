// Report card templates: the school picks a layout; every template prints the same engine figures.
const { test } = require('node:test');
const assert = require('node:assert/strict');
const path = require('node:path');
const ejs = require('ejs');
const { buildReportCards } = require('../utils/reportCardEngine');
const { resolveTemplate, decorate, TEMPLATE_IDS } = require('../utils/reportCardTemplates');
const bulletin = require('../controllers/academic/bulletinCtrl');

const school = {
    name_en: 'GOVERNMENT BILINGUAL HIGH SCHOOL', name_fr: 'LYCÉE BILINGUE', address_line: 'P.O. Box 1',
    country_en: 'REPUBLIC OF CAMEROON', motto_en: 'PEACE - WORK - FATHERLAND', ministry_en: 'MINISTRY OF SECONDARY EDUCATION',
    country_fr: 'RÉPUBLIQUE DU CAMEROUN', motto_fr: 'PAIX - TRAVAIL - PATRIE', ministry_fr: 'MINISTÈRE DES ENSEIGNEMENTS SECONDAIRES',
    logo: null, principal_signature: null, watermark_text: null, footer_text: 'Generated by KodoSchool',
};
const classroom = {
    id: '1', name: 'Form 4A', section: 'ANGLOPHONE', academic_year: '2026-2027',
    groups: [{ id: 'g1', name: 'ARTS', order: 1 }, { id: 'g2', name: 'SCIENCES', order: 2 }],
    subjects: [
        { id: 'eng', name: 'ENGLISH', group_id: 'g1', coefficient: 5, teacher_name: 'A. Tambe', order: 1 },
        { id: 'fre', name: 'FRENCH', group_id: 'g1', coefficient: 3, teacher_name: 'E. Ngwa', order: 2 },
        { id: 'mat', name: 'MATHEMATICS', group_id: 'g2', coefficient: 5, teacher_name: 'N. Fomba', order: 3 },
    ],
};
const students = ['a', 'b', 'c'].map((id, i) => ({ id, matricule: `MAT-${i}`, full_name: `Student ${id}`, date_of_birth: '2011-03-14', parent_address: 'Batouri', is_repeater: false }));
// a: strong (17), b: middling (11), c: weak (5); same mark in every sequence of every term.
const level = { a: 17, b: 11, c: 5 };
const marks = [];
for (const st of students) for (const sb of classroom.subjects) for (let q = 1; q <= 6; q++) marks.push([st.id, sb.id, q, level[st.id]]);
const cards = (term, extra = {}) => buildReportCards(school, classroom, students, marks, { term, reopening_date: '2027-09-06' }, extra);

test('the template follows an explicit choice, and "auto" follows the class section', () => {
    assert.equal(resolveTemplate('technical', 'Anglophone'), 'technical');
    assert.equal(resolveTemplate('auto', 'Francophone'), 'francophone');
    assert.equal(resolveTemplate('auto', 'ANGLOPHONE'), 'anglophone');
    assert.equal(resolveTemplate(undefined, 'Francophone'), 'classic', 'no saved choice keeps the classic card');
    assert.equal(resolveTemplate('something-else', ''), 'classic');
    assert.deepEqual(TEMPLATE_IDS, ['classic', 'anglophone', 'francophone', 'technical', 'auto']);
});

test('the engine adds the class highest and lowest averages and the pass rate', () => {
    const [card] = cards(1);
    assert.deepEqual(card.class_stats, { highest: 17, lowest: 5, pass_rate: 66.7 });
});

test('francophone wording, remark scale, annual status and council decisions on the third term', () => {
    const [strong, middling, weak] = cards(3, { discipline: { b: { warnings: 1 } } }).map(c => decorate(c, 'francophone'));
    assert.equal(strong.tpl.L.title, 'BULLETIN DE NOTES');
    assert.equal(strong.tpl.term_main, 'TROISIÈME TRIMESTRE');
    assert.equal(strong.tpl.rows[0][0].label, 'Très bien', '17/20');
    assert.equal(strong.tpl.status, 'Admis(e) en classe supérieure');
    assert.equal(strong.tpl.work_opts.find(o => o.on).label, "Tableau d'honneur + Félicitations");
    assert.deepEqual(strong.tpl.seq_labels, ['Séq. 5', 'Séq. 6']);
    // A conduct warning removes the work distinction and ticks the conduct box.
    assert.equal(middling.tpl.work_opts.some(o => o.on), false);
    assert.equal(middling.tpl.cond_opts.find(o => o.on).label, 'Avertissement conduite');
    assert.equal(weak.tpl.status, 'Redouble');
    assert.equal(weak.tpl.status_red, true);
    assert.equal(weak.tpl.work_opts.find(o => o.on).label, 'Blâme travail', 'below 6/20');
    assert.equal(weak.tpl.rows[0][0].red, true);
});

